export interface GenerateAuthSqlOptions {
  schema: string;
  roles: string[];
  bucket: string;
}

const IDENTIFIER_RE = /^[a-z][a-z0-9_]*$/;

function assertValidOptions({ schema, roles, bucket }: GenerateAuthSqlOptions): void {
  if (!IDENTIFIER_RE.test(schema)) {
    throw new Error(
      `Invalid schema name: "${schema}". Use lowercase letters, digits and underscores, starting with a letter.`
    );
  }
  if (roles.length < 2) {
    throw new Error("roles must contain at least 2 entries (lowest privilege first, highest last).");
  }
  const seen = new Set<string>();
  for (const role of roles) {
    if (!IDENTIFIER_RE.test(role)) {
      throw new Error(
        `Invalid role name: "${role}". Use lowercase letters, digits and underscores, starting with a letter.`
      );
    }
    if (seen.has(role)) {
      throw new Error(`Duplicate role name: "${role}".`);
    }
    seen.add(role);
  }
  if (!IDENTIFIER_RE.test(bucket.replace(/-/g, "_"))) {
    throw new Error(`Invalid bucket name: "${bucket}".`);
  }
}

export function generateAuthSql(options: GenerateAuthSqlOptions): string {
  assertValidOptions(options);
  const { schema, roles, bucket } = options;
  const rolesCsv = roles.map((r) => `'${r}'`).join(", ");
  const lowestRole = roles[0];
  const topRole = roles[roles.length - 1];
  const schemaCreate = schema === "public" ? "" : `create schema if not exists ${schema};\n\n`;

  return `-- Auto-generated by generateAuthSql — auth + profile + roles for schema "${schema}".
-- Roles (lowest to highest privilege): ${roles.join(", ")}.

${schemaCreate}do $$ begin
  create type ${schema}.app_role as enum (${rolesCsv});
exception when duplicate_object then null;
end $$;

create table if not exists ${schema}.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  first_name text,
  last_name text,
  avatar_url text,
  role ${schema}.app_role not null default '${lowestRole}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table ${schema}.profiles enable row level security;

create or replace function ${schema}.get_my_role()
returns ${schema}.app_role
language sql security definer stable
set search_path = ${schema}, public
as $$
  select role from ${schema}.profiles where id = auth.uid();
$$;

create or replace function ${schema}.is_admin()
returns boolean
language sql security definer stable
set search_path = ${schema}, public
as $$
  select exists (
    select 1 from ${schema}.profiles where id = auth.uid() and role = '${topRole}'
  );
$$;

create or replace function ${schema}.is_role_at_least(min_role ${schema}.app_role)
returns boolean
language sql security definer stable
set search_path = ${schema}, public
as $$
  select exists (
    select 1 from ${schema}.profiles where id = auth.uid() and role >= min_role
  );
$$;

create or replace function ${schema}.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = ${schema}, public
as $$
begin
  insert into ${schema}.profiles (id, username, first_name, last_name, role)
  values (
    new.id,
    split_part(new.email, '@', 1) || '_' || substr(new.id::text, 1, 6),
    new.raw_user_meta_data ->> 'first_name',
    new.raw_user_meta_data ->> 'last_name',
    '${lowestRole}'
  );
  return new;
end;
$$;

drop trigger if exists ${schema}_handle_new_user on auth.users;
create trigger ${schema}_handle_new_user
  after insert on auth.users
  for each row execute function ${schema}.handle_new_user();

create or replace function ${schema}.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_profiles_updated_at on ${schema}.profiles;
create trigger set_profiles_updated_at
  before update on ${schema}.profiles
  for each row execute function ${schema}.set_updated_at();

create or replace function ${schema}.prevent_role_change()
returns trigger
language plpgsql security definer
set search_path = ${schema}, public
as $$
begin
  if new.role is distinct from old.role and not ${schema}.is_admin() then
    raise exception 'Only an admin can change a user role';
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_role_change on ${schema}.profiles;
create trigger enforce_role_change
  before update on ${schema}.profiles
  for each row execute function ${schema}.prevent_role_change();

drop policy if exists "${schema}_profiles_select_all" on ${schema}.profiles;
create policy "${schema}_profiles_select_all"
  on ${schema}.profiles for select using (true);

drop policy if exists "${schema}_profiles_insert_own" on ${schema}.profiles;
create policy "${schema}_profiles_insert_own"
  on ${schema}.profiles for insert with check (auth.uid() = id);

drop policy if exists "${schema}_profiles_update_own" on ${schema}.profiles;
create policy "${schema}_profiles_update_own"
  on ${schema}.profiles for update
  using (auth.uid() = id);

drop policy if exists "${schema}_profiles_update_admin" on ${schema}.profiles;
create policy "${schema}_profiles_update_admin"
  on ${schema}.profiles for update
  using (${schema}.is_admin());

drop policy if exists "${schema}_profiles_delete_admin" on ${schema}.profiles;
create policy "${schema}_profiles_delete_admin"
  on ${schema}.profiles for delete using (${schema}.is_admin());

insert into storage.buckets (id, name, public)
values ('${bucket}', '${bucket}', true)
on conflict (id) do nothing;

drop policy if exists "${bucket}_public_read" on storage.objects;
create policy "${bucket}_public_read"
  on storage.objects for select using (bucket_id = '${bucket}');

drop policy if exists "${bucket}_write_own" on storage.objects;
create policy "${bucket}_write_own"
  on storage.objects for insert
  with check (bucket_id = '${bucket}' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "${bucket}_update_own" on storage.objects;
create policy "${bucket}_update_own"
  on storage.objects for update
  using (bucket_id = '${bucket}' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "${bucket}_delete_own" on storage.objects;
create policy "${bucket}_delete_own"
  on storage.objects for delete
  using (bucket_id = '${bucket}' and (storage.foldername(name))[1] = auth.uid()::text);

-- Manual step (dashboard, not SQL): Auth settings → enable "Leaked password protection",
-- "Confirm email", and "Secure email change". Never store the service_role key in this repo.
-- Bootstrap your first admin manually:
--   update ${schema}.profiles set role = '${topRole}' where username = 'YOUR_USERNAME';
`;
}
